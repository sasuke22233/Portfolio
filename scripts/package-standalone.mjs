import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const standaloneDir = path.join(root, ".next", "standalone");
const nextStaticDir = path.join(root, ".next", "static");
const publicDir = path.join(root, "public");

const distRoot = path.join(root, "dist");
const outDir = path.join(distRoot, "murcielago-standalone");

function rm(dir) {
  fs.rmSync(dir, { recursive: true, force: true });
}

function ensureDir(dir) {
  fs.mkdirSync(dir, { recursive: true });
}

function copyDir(src, dest) {
  fs.cpSync(src, dest, { recursive: true });
}

function assertExists(p, label) {
  if (!fs.existsSync(p)) {
    throw new Error(
      `${label} not found: ${p}\nRun: npm run build (Next standalone output required).`,
    );
  }
}

assertExists(standaloneDir, "standalone output");
assertExists(nextStaticDir, "next static output");
assertExists(publicDir, "public dir");

ensureDir(distRoot);
rm(outDir);
ensureDir(outDir);

// Copy standalone server + minimal node_modules + .next server artifacts
copyDir(standaloneDir, outDir);

// Next standalone expects .next/static and public at the same root as server.js
ensureDir(path.join(outDir, ".next"));
copyDir(nextStaticDir, path.join(outDir, ".next", "static"));
copyDir(publicDir, path.join(outDir, "public"));

const envLocal = path.join(root, ".env.local");
const envProd = path.join(root, ".env.production");
if (fs.existsSync(envProd)) fs.copyFileSync(envProd, path.join(outDir, ".env.production"));
else if (fs.existsSync(envLocal)) fs.copyFileSync(envLocal, path.join(outDir, ".env.local"));

const marker = [
  "This folder was generated by scripts/package-standalone.mjs",
  "Upload this folder to your server and run `node server.js`.",
].join("\n");
fs.writeFileSync(path.join(outDir, "_DEPLOY_PACKAGE.txt"), `${marker}\n`);

console.log(`✅ Packaged standalone app to: ${outDir}`);
